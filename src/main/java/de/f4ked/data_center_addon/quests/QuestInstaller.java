package de.f4ked.data_center_addon.quests;

import com.mojang.logging.LogUtils;
import de.f4ked.data_center_addon.Config;
import de.f4ked.data_center_addon.Data_center_addon;
import net.minecraft.nbt.CompoundTag;
import net.minecraft.nbt.ListTag;
import net.minecraft.nbt.StringTag;
import net.minecraft.nbt.Tag;
import net.neoforged.bus.api.EventPriority;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.fml.ModList;
import net.neoforged.fml.common.EventBusSubscriber;
import net.neoforged.fml.loading.FMLPaths;
import net.neoforged.neoforge.event.server.ServerAboutToStartEvent;
import org.jetbrains.annotations.Nullable;
import org.slf4j.Logger;

import java.io.IOException;
import java.io.InputStream;
import java.lang.reflect.Method;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.Arrays;
import java.util.List;
import java.util.Properties;

/**
 * Installs the add-on's FTB Quests chapters (a guide and a release calendar, generated by
 * {@code tools/generate-quests.py}) into the quest book of the instance.
 * <p>
 * FTB Quests reads {@code config/ftbquests/quests} when the server has started; this runs just before
 * that. It copies the add-on's chapter files, adds its two chapter groups and merges its titles and
 * texts into the lang files. Nothing else in the quest book is touched. A marker file remembers which
 * version is installed, so the chapters are only rewritten when the add-on brings new ones, and a
 * chapter the pack maker deleted is not brought back until then. {@code installQuests = false} in the
 * config turns it off.
 * <p>
 * FTB Library's SNBT reader and writer are used through reflection, so FTB Quests stays optional.
 */
@EventBusSubscriber(modid = Data_center_addon.MODID)
public final class QuestInstaller {
    private static final Logger LOGGER = LogUtils.getLogger();
    private static final String SOURCE = "data_center_addon_quests/";
    private static final String MARKER = ".data_center_addon_quests";

    private QuestInstaller() {
    }

    @SubscribeEvent(priority = EventPriority.HIGHEST)
    static void onServerAboutToStart(ServerAboutToStartEvent event) {
        if (!ModList.get().isLoaded("ftbquests") || !Config.installQuests()) {
            return;
        }
        try {
            install(FMLPaths.CONFIGDIR.get().resolve("ftbquests/quests"));
        } catch (Exception e) {
            LOGGER.error("Could not install the Data Center AddOn quests", e);
        }
    }

    private static void install(Path folder) throws Exception {
        Properties manifest = new Properties();
        try (InputStream in = resource("manifest.properties")) {
            if (in == null) {
                return;
            }
            manifest.load(in);
        }
        String hash = manifest.getProperty("hash", "");
        Path marker = folder.resolve(MARKER);
        if (Files.exists(marker) && Files.readString(marker, StandardCharsets.UTF_8).trim().equals(hash)) {
            return;
        }
        Snbt snbt = Snbt.find();
        if (snbt == null) {
            LOGGER.warn("FTB Library's SNBT not found; Data Center AddOn quests not installed");
            return;
        }

        Files.createDirectories(folder.resolve("chapters"));
        for (String chapter : list(manifest, "chapters")) {
            try (InputStream in = resource("chapters/" + chapter + ".snbt")) {
                if (in != null) {
                    Files.copy(in, folder.resolve("chapters/" + chapter + ".snbt"), StandardCopyOption.REPLACE_EXISTING);
                }
            }
        }

        // chapter groups, appended after the pack's own
        Path groupsFile = folder.resolve("chapter_groups.snbt");
        CompoundTag groups = Files.exists(groupsFile) ? snbt.read(groupsFile) : null;
        if (groups == null) {
            groups = new CompoundTag();
        }
        ListTag groupList = groups.getList("chapter_groups", Tag.TAG_COMPOUND);
        for (String id : list(manifest, "groups")) {
            boolean present = false;
            for (Tag tag : groupList) {
                if (tag instanceof CompoundTag group && id.equalsIgnoreCase(group.getString("id"))) {
                    present = true;
                }
            }
            if (!present) {
                CompoundTag group = new CompoundTag();
                group.putString("id", id);
                groupList.add(group);
            }
        }
        groups.put("chapter_groups", groupList);
        snbt.write(groupsFile, groups);

        // titles and texts: the add-on's keys win, all other keys stay
        Files.createDirectories(folder.resolve("lang"));
        for (String locale : list(manifest, "locales")) {
            CompoundTag ours;
            try (InputStream in = resource("lang/" + locale + ".snbt")) {
                if (in == null) {
                    continue;
                }
                ours = snbt.readLines(Arrays.asList(new String(in.readAllBytes(), StandardCharsets.UTF_8).split("\\R")));
            }
            if (ours == null) {
                continue;
            }
            Path langFile = folder.resolve("lang/" + locale + ".snbt");
            CompoundTag existing = Files.exists(langFile) ? snbt.read(langFile) : null;
            if (existing == null) {
                existing = new CompoundTag();
            }
            for (String key : ours.getAllKeys()) {
                Tag value = ours.get(key);
                existing.put(key, value == null ? StringTag.valueOf("") : value.copy());
            }
            snbt.write(langFile, existing);
        }

        Files.writeString(marker, hash, StandardCharsets.UTF_8);
        LOGGER.info("Installed the Data Center AddOn quests ({} chapters) into {}", list(manifest, "chapters").size(), folder);
    }

    @Nullable
    private static InputStream resource(String path) throws IOException {
        Path file = ModList.get().getModFileById(Data_center_addon.MODID).getFile().findResource(SOURCE + path);
        return Files.exists(file) ? Files.newInputStream(file) : null;
    }

    private static List<String> list(Properties manifest, String key) {
        String value = manifest.getProperty(key, "");
        return value.isBlank() ? List.of() : Arrays.asList(value.split(","));
    }

    /** FTB Library's {@code dev.ftb.mods.ftblibrary.snbt.SNBT}, called by reflection. */
    private record Snbt(Method read, Method readLines, Method write) {
        @Nullable
        static Snbt find() {
            try {
                Class<?> type = Class.forName("dev.ftb.mods.ftblibrary.snbt.SNBT");
                return new Snbt(type.getMethod("read", Path.class), type.getMethod("readLines", List.class),
                        type.getMethod("write", Path.class, CompoundTag.class));
            } catch (ReflectiveOperationException e) {
                return null;
            }
        }

        @Nullable
        CompoundTag read(Path path) throws ReflectiveOperationException {
            return (CompoundTag) read.invoke(null, path);
        }

        @Nullable
        CompoundTag readLines(List<String> lines) throws ReflectiveOperationException {
            return (CompoundTag) readLines.invoke(null, lines);
        }

        void write(Path path, CompoundTag tag) throws ReflectiveOperationException {
            if (!(Boolean) write.invoke(null, path, tag)) {
                throw new IllegalStateException("could not write " + path);
            }
        }
    }
}
